#!/usr/bin/env node
/* global process, console */
/* eslint-disable no-console */
// Regenerate scripts/host-reexports-floor.json, the ReExports list of the
// OLDEST host the bundle has to load on (the first entry of the host-compat
// probe's DEFAULT_VERSIONS). esbuild.mjs externalizes only paths on that list,
// so a path the installed @jbrowse/core re-exports but an old host does not gets
// bundled instead of resolving to undefined there.
//
// Usage: node scripts/update-host-reexports-floor.mjs [4.0.0]
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const version = process.argv[2] ?? '4.0.0'
const out = path.join(import.meta.dirname, 'host-reexports-floor.json')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jbrowse-core-'))

// npm has reported --json as an array and as an object keyed by package name
const packed = JSON.parse(
  execFileSync(
    'npm',
    ['pack', `@jbrowse/core@${version}`, '--pack-destination', tmp, '--json'],
    { encoding: 'utf8' },
  ),
)
const { filename } = Array.isArray(packed)
  ? packed[0]
  : Object.values(packed)[0]
execFileSync('tar', ['-xzf', path.join(tmp, filename), '-C', tmp])

const list = path.join(tmp, 'package/esm/ReExports/list.js')
const paths = (await import(list)).default
if (!Array.isArray(paths) || paths.length === 0) {
  throw new Error(`${list} did not export a list`)
}

fs.writeFileSync(
  out,
  `${JSON.stringify(
    {
      comment:
        'GENERATED by scripts/update-host-reexports-floor.mjs -- do not edit by hand',
      version,
      paths: [...paths].sort(),
    },
    null,
    2,
  )}\n`,
)
fs.rmSync(tmp, { recursive: true, force: true })
console.log(`Wrote ${paths.length} paths from @jbrowse/core@${version}`)
